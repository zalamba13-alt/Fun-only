-- Internal admin check used only inside security-definer RPCs.
create or replace function public._is_quiz_admin()
returns boolean language sql stable security definer
set search_path = public
as $$ select exists(select 1 from public.admin_users where user_id = auth.uid()); $$;
revoke all on function public._is_quiz_admin() from public;

-- Public wrapper so the UI can check "am I an allowlisted admin?".
create or replace function public.is_quiz_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select public._is_quiz_admin(); $$;
revoke all on function public.is_quiz_admin() from public;
grant execute on function public.is_quiz_admin() to authenticated;

-- Check whether a name is eligible. This is informational; start_quiz_attempt
-- also enforces the rule atomically.
create or replace function public.check_quiz_attempt(p_name text)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare r public.players%rowtype;
begin
 select * into r from public.players where lower(name)=lower(btrim(coalesce(p_name,'')));
 if not found then return jsonb_build_object('taken',false,'attempts',0,'allowed',true); end if;
 return jsonb_build_object(
   'taken', r.submitted and not r.retake_allowed,
   'attempts', r.attempts,
   'allowed', (not r.submitted) or r.retake_allowed
 );
end; $$;

-- Reserve one attempt and issue an unguessable per-attempt token.
create or replace function public.start_quiz_attempt(p_name text)
returns jsonb language plpgsql security definer set search_path = public, extensions
as $$
declare n text := btrim(coalesce(p_name,'')); r public.players%rowtype; tok uuid := gen_random_uuid();
begin
 if char_length(n)<2 or char_length(n)>20 then return jsonb_build_object('ok',false,'error','invalid_name'); end if;
 insert into public.players(name,attempts,retake_allowed,last_attempt,attempt_token,submitted)
 values(n,1,false,now(),tok,false)
  on conflict (lower(name)) do update set
    attempts=public.players.attempts+1,
    retake_allowed=false,
    last_attempt=now(),
    attempt_token=tok,
    submitted=false
  -- Blocked only once the name has a SUBMITTED score. An attempt that was
  -- started and then abandoned (tab closed, refresh) may be resumed, otherwise
  -- the player would be locked out with no score on the board.
  where public.players.submitted=false or public.players.retake_allowed=true
  returning * into r;
 if not found then return jsonb_build_object('ok',false,'error','already_played'); end if;
 return jsonb_build_object('ok',true,'attempt_token',tok);
end; $$;

-- Score the submitted index map on the server, once per reservation.
create or replace function public.submit_quiz_attempt(p_name text,p_attempt_token uuid,p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare n text := btrim(coalesce(p_name,'')); r public.players%rowtype; total_q int; points int; saved public.scores%rowtype;
begin
 select * into r from public.players where lower(name)=lower(n) for update;
 if not found or r.attempt_token is distinct from p_attempt_token then return jsonb_build_object('ok',false,'error','invalid_attempt'); end if;
 if r.submitted then return jsonb_build_object('ok',false,'error','already_submitted'); end if;
 if jsonb_typeof(p_answers)<>'object' then return jsonb_build_object('ok',false,'error','invalid_answers'); end if;
 select count(*),
        count(*) filter (
          where jsonb_typeof(p_answers->question_id::text)='number'
            and (p_answers->>question_id::text)::numeric = answer_index
        )
 into total_q,points from public.quiz_answer_key;
 if total_q=0 then return jsonb_build_object('ok',false,'error','answer_key_missing'); end if;
  update public.players set submitted=true where lower(name)=lower(n);
  -- Use the stored (canonical) name so the board and the player table always match.
  insert into public.scores(name,score,total) values(r.name,points,total_q) returning * into saved;
  return jsonb_build_object(
    'ok',true,
    'score',saved.score,
    'total',saved.total,
    'created_at',saved.created_at,
    'key',(select jsonb_object_agg(question_id::text, answer_index) from public.quiz_answer_key)
  );
end; $$;

-- Admin-only operations: Supabase Auth user must be explicitly allowlisted.
create or replace function public.admin_grant_quiz_retake(p_name text)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare n text:=btrim(coalesce(p_name,''));
begin
 if not public._is_quiz_admin() then raise exception 'not authorized'; end if;
 if char_length(n)<2 or char_length(n)>20 then raise exception 'invalid name'; end if;
  insert into public.players(name,attempts,retake_allowed,last_attempt,submitted)
  values(n,0,true,now(),false)
  on conflict (lower(name)) do update set retake_allowed=true;
  return jsonb_build_object('ok',true);
end; $$;
create or replace function public.admin_remove_quiz_player(p_name text)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare n text:=btrim(coalesce(p_name,''));
begin
 if not public._is_quiz_admin() then raise exception 'not authorized'; end if;
 delete from public.scores where lower(name)=lower(n);
 delete from public.players where lower(name)=lower(n);
 return jsonb_build_object('ok',true);
end; $$;
create or replace function public.admin_list_quiz_players()
returns jsonb language plpgsql security definer set search_path = public
as $$
declare players jsonb;
begin
 if not public._is_quiz_admin() then raise exception 'not authorized'; end if;
 select coalesce(jsonb_agg(
   jsonb_build_object(
     'name', p.name,
     'attempts', p.attempts,
     'retake_allowed', p.retake_allowed,
     'last_attempt', p.last_attempt,
     'submitted', p.submitted
   ) order by p.name
 ), '[]'::jsonb)
 into players from public.players p;
 return players;
end; $$;
create or replace function public.admin_clear_quiz_board()
returns jsonb language plpgsql security definer set search_path = public
as $$
begin
 if not public._is_quiz_admin() then raise exception 'not authorized'; end if;
 delete from public.scores;
 delete from public.players;
 return jsonb_build_object('ok',true);
end; $$;

