/*
 * LEADERBOARD STORE
 * -----------------
 * Two modes, chosen automatically:
 *
 *   1. LOCAL  (default)  — scores live in this browser only.
 *   2. SHARED            — scores live in Supabase so every player sees one board.
 *
 * To switch to SHARED, create a free Supabase project (no card needed),
 * run the SQL below in the SQL editor, then paste your project URL and
 * anon key into REMOTE. Nothing else to change.
 *
 * ------------------------------------------------------------------
 * SQL — run once in Supabase → SQL Editor → New query
 * ------------------------------------------------------------------
 *
 *   -- scores: one row per attempt
 *   create table if not exists scores (
 *     id bigint generated by default as identity primary key,
 *     name text not null,
 *     score int not null,
 *     total int not null,
 *     created_at timestamptz not null default now()
 *   );
 *
 *   -- players: one row per person, tracks attempts and permission to retake
 *   create table if not exists players (
 *     name text primary key,
 *     attempts int not null default 0,
 *     retake_allowed boolean not null default false,
 *     last_attempt timestamptz
 *   );
 *
 *   alter table scores  enable row level security;
 *   alter table players enable row level security;
 *
 *   create policy "read scores"    on scores  for select using (true);
 *   create policy "insert scores"  on scores  for insert with check (true);
 *   create policy "delete scores"  on scores  for delete using (true);
 *   create policy "read players"   on players for select using (true);
 *   create policy "upsert players" on players for insert with check (true);
 *   create policy "update players" on players for update using (true);
 *   create policy "delete players" on players for delete using (true);
 *
 * ------------------------------------------------------------------
 * NOTE: these policies are open (anyone can insert or delete). That is
 * fine for a fun quiz among friends. The admin password below is a soft
 * gate, not real security — a determined person could bypass it.
 */

const Store = (function () {
  'use strict';

  /* ================== CONFIGURE ME ================== */

  const REMOTE = {
    url: 'https://elwysrmcuysgvpqsvryu.supabase.co',
    anonKey: 'sb_publishable_8vmqAkbzqj4XgSHtkoW7Eg_-WooCPf9',
    scores: 'scores',
    players: 'players'
  };

  // Change this to whatever you want. Used to unlock the admin panel.
  const ADMIN_PASSWORD = 'tobi2026';

  /* ================================================== */

  const KEY_SCORES = 'tobi_scores_v2';
  const KEY_PLAYERS = 'tobi_players_v2';
  const KEY_UNLOCK = 'tobi_admin_unlocked';
  const LIMIT = 100;

  function isRemote() {
    return Boolean(REMOTE.url && REMOTE.anonKey);
  }

  function base() {
    return REMOTE.url.replace(/\/+$/, '') + '/rest/v1/';
  }

  function headers(extra) {
    return Object.assign(
      {
        apikey: REMOTE.anonKey,
        Authorization: 'Bearer ' + REMOTE.anonKey
      },
      extra || {}
    );
  }

  function cleanName(name) {
    return String(name || 'Anonymous').trim().slice(0, 20) || 'Anonymous';
  }

  /* ---------------- local storage helpers ---------------- */

  function readJson(key, fallback) {
    try {
      const raw = localStorage.getItem(key);
      if (!raw) return fallback;
      const parsed = JSON.parse(raw);
      return parsed === null || parsed === undefined ? fallback : parsed;
    } catch (err) {
      return fallback;
    }
  }

  function writeJson(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch (err) {
      /* storage full or blocked — nothing sensible to do */
    }
  }

  function readLocalScores() {
    const rows = readJson(KEY_SCORES, []);
    return Array.isArray(rows) ? rows : [];
  }

  function readLocalPlayers() {
    const map = readJson(KEY_PLAYERS, {});
    return map && typeof map === 'object' ? map : {};
  }

  /* ---------------- ordering ---------------- */

  function sortRows(rows) {
    return rows.slice().sort(function (a, b) {
      if (b.score !== a.score) return b.score - a.score;
      return new Date(a.created_at) - new Date(b.created_at);
    });
  }

  function normaliseScores(rows) {
    return sortRows(rows).slice(0, LIMIT).map(function (r) {
      return {
        name: cleanName(r.name),
        score: Number(r.score) || 0,
        total: Number(r.total) || 0,
        created_at: r.created_at || new Date().toISOString()
      };
    });
  }

  /* ---------------- scores ---------------- */

  async function listScores() {
    if (!isRemote()) return normaliseScores(readLocalScores());

    try {
      const res = await fetch(
        base() + REMOTE.scores +
          '?select=name,score,total,created_at&order=score.desc,created_at.asc&limit=' + LIMIT,
        { headers: headers() }
      );
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const rows = await res.json();
      if (!Array.isArray(rows)) throw new Error('Unexpected response');
      return normaliseScores(rows);
    } catch (err) {
      console.warn('[leaderboard] shared board unavailable, using this device.', err);
      return normaliseScores(readLocalScores());
    }
  }

  async function addScore(entry) {
    const row = {
      name: cleanName(entry.name),
      score: Number(entry.score) || 0,
      total: Number(entry.total) || 0,
      created_at: new Date().toISOString()
    };

    if (!isRemote()) {
      const local = readLocalScores();
      local.unshift(row);
      writeJson(KEY_SCORES, local.slice(0, 200));
      return { shared: false, row: row };
    }

    try {
      const res = await fetch(base() + REMOTE.scores, {
        method: 'POST',
        headers: headers({
          'Content-Type': 'application/json',
          Prefer: 'return=representation'
        }),
        body: JSON.stringify({
          name: row.name,
          score: row.score,
          total: row.total
        })
      });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const saved = await res.json();
      if (Array.isArray(saved) && saved[0] && saved[0].created_at) {
        row.created_at = saved[0].created_at;
      }
      return { shared: true, row: row };
    } catch (err) {
      console.warn('[leaderboard] could not save to the shared board.', err);
      const local = readLocalScores();
      local.unshift(row);
      writeJson(KEY_SCORES, local.slice(0, 200));
      return { shared: false, row: row };
    }
  }

  /* ---------------- players / attempts ---------------- */

  function localPlayer(map, name) {
    const key = name.toLowerCase();
    if (!map[key]) map[key] = { name: name, attempts: 0, retake_allowed: false };
    return map[key];
  }

  /**
   * Has this person already taken the quiz?
   * Returns { taken, attempts, allowed }.
   */
  async function attemptStatus(name) {
    const clean = cleanName(name);

    if (!isRemote()) {
      const map = readLocalPlayers();
      const rec = map[clean.toLowerCase()];
      if (!rec) return { taken: false, attempts: 0, allowed: true };
      return {
        taken: rec.attempts > 0,
        attempts: rec.attempts,
        allowed: rec.retake_allowed === true
      };
    }

    try {
      const res = await fetch(
        base() + REMOTE.players + '?select=attempts,retake_allowed&name=eq.' +
          encodeURIComponent(clean),
        { headers: headers() }
      );
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const rows = await res.json();
      const rec = Array.isArray(rows) ? rows[0] : null;
      if (!rec) return { taken: false, attempts: 0, allowed: true };
      return {
        taken: Number(rec.attempts) > 0,
        attempts: Number(rec.attempts) || 0,
        allowed: rec.retake_allowed === true
      };
    } catch (err) {
      console.warn('[leaderboard] could not check attempts.', err);
      // Fail open so a network blip never locks someone out of the quiz.
      return { taken: false, attempts: 0, allowed: true };
    }
  }

  /** Record that this person has started/completed an attempt. */
  async function recordAttempt(name) {
    const clean = cleanName(name);

    if (!isRemote()) {
      const map = readLocalPlayers();
      const rec = localPlayer(map, clean);
      rec.attempts += 1;
      rec.retake_allowed = false;
      writeJson(KEY_PLAYERS, map);
      return;
    }

    try {
      await fetch(base() + REMOTE.players + '?on_conflict=name', {
        method: 'POST',
        headers: headers({
          'Content-Type': 'application/json',
          Prefer: 'resolution=merge-duplicates'
        }),
        body: JSON.stringify({
          name: clean,
          attempts: 1,
          retake_allowed: false,
          last_attempt: new Date().toISOString()
        })
      });
    } catch (err) {
      console.warn('[leaderboard] could not record the attempt.', err);
    }
  }

  /* ---------------- admin ---------------- */

  function isUnlocked() {
    try {
      return sessionStorage.getItem(KEY_UNLOCK) === '1';
    } catch (err) {
      return false;
    }
  }

  function unlock(password) {
    const ok = String(password || '') === ADMIN_PASSWORD;
    if (ok) {
      try {
        sessionStorage.setItem(KEY_UNLOCK, '1');
      } catch (err) {
        /* ignore */
      }
    }
    return ok;
  }

  function lock() {
    try {
      sessionStorage.removeItem(KEY_UNLOCK);
    } catch (err) {
      /* ignore */
    }
  }

  /** Allow one person to take the quiz again. */
  async function grantRetake(name) {
    if (!isUnlocked()) return false;
    const clean = cleanName(name);

    if (!isRemote()) {
      const map = readLocalPlayers();
      const rec = localPlayer(map, clean);
      rec.retake_allowed = true;
      writeJson(KEY_PLAYERS, map);
      return true;
    }

    try {
      const res = await fetch(base() + REMOTE.players + '?on_conflict=name', {
        method: 'POST',
        headers: headers({
          'Content-Type': 'application/json',
          Prefer: 'resolution=merge-duplicates'
        }),
        body: JSON.stringify({ name: clean, retake_allowed: true })
      });
      return res.ok;
    } catch (err) {
      console.warn('[leaderboard] could not grant a retake.', err);
      return false;
    }
  }

  /** Remove every score for a person (admin). */
  async function removePlayer(name) {
    if (!isUnlocked()) return false;
    const clean = cleanName(name);

    if (!isRemote()) {
      const scores = readLocalScores().filter(function (r) {
        return r.name.toLowerCase() !== clean.toLowerCase();
      });
      writeJson(KEY_SCORES, scores);

      const map = readLocalPlayers();
      delete map[clean.toLowerCase()];
      writeJson(KEY_PLAYERS, map);
      return true;
    }

    try {
      const s = await fetch(
        base() + REMOTE.scores + '?name=eq.' + encodeURIComponent(clean),
        { method: 'DELETE', headers: headers() }
      );
      const p = await fetch(
        base() + REMOTE.players + '?name=eq.' + encodeURIComponent(clean),
        { method: 'DELETE', headers: headers() }
      );
      return s.ok && p.ok;
    } catch (err) {
      console.warn('[leaderboard] could not remove the player.', err);
      return false;
    }
  }

  /** Clear the whole board (admin). */
  async function clearAll() {
    if (!isUnlocked()) return false;

    if (!isRemote()) {
      writeJson(KEY_SCORES, []);
      writeJson(KEY_PLAYERS, {});
      return true;
    }

    try {
      const s = await fetch(base() + REMOTE.scores + '?id=gt.0', {
        method: 'DELETE',
        headers: headers()
      });
      const p = await fetch(base() + REMOTE.players + '?name=not.is.null', {
        method: 'DELETE',
        headers: headers()
      });
      return s.ok && p.ok;
    } catch (err) {
      console.warn('[leaderboard] could not clear the board.', err);
      return false;
    }
  }

  return {
    listScores: listScores,
    addScore: addScore,
    attemptStatus: attemptStatus,
    recordAttempt: recordAttempt,
    grantRetake: grantRetake,
    removePlayer: removePlayer,
    clearAll: clearAll,
    isRemote: isRemote,
    isUnlocked: isUnlocked,
    unlock: unlock,
    lock: lock,
    LIMIT: LIMIT
  };
})();
